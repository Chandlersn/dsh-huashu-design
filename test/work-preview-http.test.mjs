import test from 'node:test';
import assert from 'node:assert/strict';
import * as fs from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import { createServer } from 'node:http';
import { once } from 'node:events';
import { createOperations } from '../lib/core.js';
import { createHttpHandler } from '../lib/host.js';

const png = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+j7xkAAAAASUVORK5CYII=', 'base64');
test('Huashu owns HTML preview, thumbnails and source writes without loosening file-download policy', async t => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'huashu-work-preview-http-'));
  const operations = createOperations({ dshHome: path.join(root, 'home') });
  const file = path.join(root, 'article.html'), image = path.join(root, 'assets', 'pixel.png'), thumbnail = path.join(root, 'article-desktop.png');
  await fs.mkdir(path.dirname(image)); await fs.writeFile(image, png); await fs.writeFile(thumbnail, png);
  const original = '<!doctype html><html><head><title>Article</title></head><body><h1 data-pp-edit="title">Original</h1><img src="assets/pixel.png"><script>window.localInteraction=true</script></body></html>';
  await fs.writeFile(file, original);
  const { item } = await operations.operation('add', { title: 'Article', path: file, sourcePath: file, module: 'web' });
  let origin;
  const server = createServer(createHttpHandler(operations, { requestRejection: req => req.headers.authorization === 'test-owner' ? undefined : 401 }, () => origin));
  server.listen(0, '127.0.0.1'); await once(server, 'listening'); origin = `http://127.0.0.1:${server.address().port}`;
  t.after(async () => {
    server.closeAllConnections?.(); await new Promise(resolve => server.close(resolve));
    assert.equal(path.dirname(root), path.resolve(os.tmpdir())); assert.ok(path.basename(root).startsWith('huashu-work-preview-http-'));
    await fs.rm(root, { recursive: true, force: true });
  });
  const post = (action, args, extra = {}) => fetch(origin + '/huashu-design/api/action', { method: 'POST', headers: { authorization: 'test-owner', origin, 'content-type': 'application/json', ...extra }, body: JSON.stringify({ action, args }) });
  assert.equal((await post('preview', { id: item.id }, { authorization: '' })).status, 401);
  assert.equal((await post('preview', { id: item.id }, { origin: 'https://other.example' })).status, 403);
  const response = await post('preview', { id: item.id });
  assert.equal(response.status, 200); assert.match(response.headers.get('content-type'), /application\/json/);
  const preview = await response.json();
  assert.equal(preview.kind, 'html'); assert.equal(preview.workId, item.id); assert.equal(preview.sourcePath, file);
  assert.match(preview.html, /data:image\/png;base64,/); assert.match(preview.html, /window.localInteraction=true/);
  assert.doesNotMatch(preview.html, /guizang-design/);
  assert.equal(await fs.readFile(file, 'utf8'), original, 'preview generation must not change the actual source');
  const thumbnailUrl = origin + `/huashu-design/works/${item.id}/thumbnail`;
  assert.equal((await fetch(thumbnailUrl)).status, 401);
  const cover = await fetch(thumbnailUrl, { headers: { authorization: 'test-owner' } });
  assert.equal(cover.status, 200); assert.match(cover.headers.get('content-type'), /image\/png/);
  assert.deepEqual(Buffer.from(await cover.arrayBuffer()), png);
  const head = await fetch(thumbnailUrl, { method: 'HEAD', headers: { authorization: 'test-owner' } });
  assert.equal(head.status, 200); assert.equal(head.headers.get('content-length'), String(png.length)); assert.equal((await head.arrayBuffer()).byteLength, 0);
  const download = await fetch(origin + item.url, { headers: { authorization: 'test-owner' } });
  assert.match(download.headers.get('content-disposition'), /^attachment;/, 'registered HTML remains a safe attachment outside the sandbox viewer');
  const source = await (await post('source', { id: item.id, sourcePath: file })).json();
  const content = source.content.replace('Original', 'Edited');
  const saved = await post('source', { id: item.id, sourcePath: file, revision: source.revision, content });
  assert.equal(saved.status, 200); const savedResult = await saved.json();
  assert.equal(await fs.readFile(file, 'utf8'), content); assert.equal(await fs.readFile(savedResult.backupPath, 'utf8'), original);
  assert.equal((await operations.operation('list')).total, 1);
  assert.equal((await post('source', { id: item.id, sourcePath: path.join(root, 'other.html') })).status, 403);
});
