import { build } from 'esbuild';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const target = path.join(root, 'lib/client.js');
const result = await build({
  absWorkingDir: root,
  entryPoints: ['src/client.js'],
  outfile: target,
  bundle: true,
  format: 'iife',
  platform: 'browser',
  target: ['es2022'],
  charset: 'utf8',
  minify: false,
  legalComments: 'inline',
  logOverride: { 'duplicate-object-key': 'error' },
  loader: { '.css': 'text' },
  define: { 'process.env.NODE_ENV': '"production"' },
  write: false,
  metafile: true,
  banner: { js: '// Generated by scripts/build-client.mjs. Edit src/client.js and lib/handbook.js.' },
});
// Fingerprint every real bundled input (including themes and shared adapters),
// even when an edit changes only data/comments that the bundler can remove.
const inputHash = createHash('sha256');
const inputPaths = [...new Set([...Object.keys(result.metafile.inputs), 'scripts/build-client.mjs'])].sort();
for (const input of inputPaths) inputHash.update(input).update(await readFile(path.resolve(root, input)));
const output = Buffer.concat([Buffer.from(`// Source inputs SHA-256: ${inputHash.digest('hex')}\n`), result.outputFiles[0].contents]);
const license = await readFile(new URL('../LICENSE.md', import.meta.resolve('marked')));
const licenseTarget = path.join(root, 'dist/marked-LICENSE.md');
if (Object.values(result.metafile.outputs).some(item => item.imports.length)) throw new Error('Client artifact must not have unresolved module imports.');
if (process.argv.includes('--check')) {
  let existing, existingLicense;
  try { existing = await readFile(target); existingLicense = await readFile(licenseTarget); } catch {}
  if (!existing?.equals(Buffer.from(output)) || !existingLicense?.equals(license)) {
    console.error('Client artifact is missing or stale. Run npm run build.');
    process.exitCode = 1;
  } else console.log('Client artifact matches the current source and Markdown dependency.');
} else {
  await mkdir(path.dirname(target), { recursive: true });
  await writeFile(target, output);
  await writeFile(licenseTarget, license);
  console.log(`Built lib/client.js (${output.length} bytes).`);
}
